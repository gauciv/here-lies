"""Pack the frames Here Lies uses from 0x72's 16x16 DungeonTileset II (CC0) into
one atlas PNG plus a TypeScript manifest.

Usage: python3 tools/build_atlas.py <path to 0x72_DungeonTilesetII_v1.7>
Source: https://0x72.itch.io/dungeontileset-ii (Creative Commons Zero v1.0)
"""
import os
import sys
from PIL import Image

HERO = 'dwarf_m'
FRAMES = (
    [f'floor_{i}' for i in range(1, 9)]
    + ['hole', 'skull', 'floor_stairs', 'edge_down']
    + ['wall_mid', 'wall_top_mid', 'wall_left', 'wall_right', 'wall_banner_red', 'wall_banner_blue']
    + ['wall_fountain_top_1']
    + [f'wall_fountain_mid_red_anim_f{i}' for i in range(3)]
    + [f'wall_fountain_basin_red_anim_f{i}' for i in range(3)]
    + ['doors_frame_left', 'doors_frame_right', 'doors_frame_top', 'doors_leaf_closed', 'doors_leaf_open']
    + [f'{HERO}_idle_anim_f{i}' for i in range(4)]
    + [f'{HERO}_run_anim_f{i}' for i in range(4)]
)

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT_PNG = os.path.join(ROOT, 'src', 'client', 'assets', 'dungeon.png')
OUT_TS = os.path.join(ROOT, 'src', 'client', 'engine', 'atlas.ts')
WIDTH = 256


def main(src: str) -> None:
    images = [(name, Image.open(os.path.join(src, 'frames', f'{name}.png')).convert('RGBA')) for name in FRAMES]
    # shelf packing, tallest first
    order = sorted(images, key=lambda t: -t[1].height)
    x = y = shelf = 0
    rects = {}
    for name, im in order:
        if x + im.width > WIDTH:
            x, y, shelf = 0, y + shelf, 0
        rects[name] = (x, y, im.width, im.height)
        x += im.width
        shelf = max(shelf, im.height)
    atlas = Image.new('RGBA', (WIDTH, y + shelf), (0, 0, 0, 0))
    for name, im in images:
        rx, ry, _, _ = rects[name]
        atlas.alpha_composite(im, (rx, ry))
    os.makedirs(os.path.dirname(OUT_PNG), exist_ok=True)
    atlas.save(OUT_PNG, optimize=True)

    lines = [
        '// Generated by tools/build_atlas.py from 0x72 DungeonTileset II (CC0). Do not edit.',
        f"export const HERO = '{HERO}';",
        '',
        'export const FRAMES = {',
    ]
    for name in FRAMES:
        rx, ry, w, h = rects[name]
        lines.append(f'  {name}: [{rx}, {ry}, {w}, {h}],')
    lines += ['} as const;', '', 'export type FrameName = keyof typeof FRAMES;', '']
    for kind in ('idle', 'run'):
        names = ', '.join(f"'{HERO}_{kind}_anim_f{i}'" for i in range(4))
        lines.append(f'export const HERO_{kind.upper()}: readonly FrameName[] = [{names}];')
    lines.append('')
    with open(OUT_TS, 'w') as f:
        f.write('\n'.join(lines))
    print(f'atlas {atlas.size} with {len(FRAMES)} frames')


if __name__ == '__main__':
    main(sys.argv[1])
